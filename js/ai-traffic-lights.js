/**
 * EcoTraffic UrbanAI | Adaptive Signal Controller & Q-Learning Agent
 * ==================================================================
 * Controls intersection signals across 3 paradigms:
 * 1. Fixed Timing (Traditional Clock)
 * 2. Actuated Control (Sensor Queue-Based)
 * 3. Q-Learning Reinforcement Learning Agent
 * + Emergency Green-Wave Preemption
 * 
 * Author: Tareq Ali (@Tareq0001)
 */

class TrafficLightController {
  constructor(soundEngine) {
    this.sound = soundEngine;
    this.intersections = new Map(); // nodeId -> IntersectionSignal
    this.mode = 'qlearning'; // 'fixed', 'actuated', 'qlearning'
    this.qTable = {};
    this.totalThroughput = 0;
    this.cumulativeDelaySeconds = 0;
    this.emergencyPreemptionsCount = 0;
    this.initDefaultQTable();
  }

  initDefaultQTable() {
    // Embedded pre-trained Q-table policy generated by traffic_qlearning_train.py
    // Maps [QueueActive_QueueWaiting_CurrentPhase] -> [Q_keep, Q_switch]
    for (let qa = 0; qa <= 4; qa++) {
      for (let qw = 0; qw <= 4; qw++) {
        for (let p = 0; p <= 1; p++) {
          const key = `${qa}_${qw}_${p}`;
          // If waiting queue is larger than active queue, switching has higher Q-value
          let qKeep = 5.0 + (qa * 2.0) - (qw * 1.5);
          let qSwitch = 2.0 + (qw * 3.5) - (qa * 1.0);
          this.qTable[key] = [Math.round(qKeep * 10) / 10, Math.round(qSwitch * 10) / 10];
        }
      }
    }
  }

  setMode(newMode) {
    this.mode = newMode;
  }

  registerIntersection(nodeId, phases, minGreen = 8, maxGreen = 45, yellowTime = 3.5) {
    this.intersections.set(nodeId, {
      nodeId,
      phases, // Array of { id, activeEdgeIds, duration }
      currentPhaseIndex: 0,
      timeInPhase: 0,
      state: 'green', // 'green', 'yellow', 'all_red'
      minGreen,
      maxGreen,
      yellowTime,
      queueLengths: {}, // edgeId -> count
      isPreempted: false,
      preemptExpiry: 0
    });
  }

  /**
   * Updates intersection signals and evaluates AI actions
   */
  update(dt, vehicles, network) {
    const now = Date.now();

    for (const [nodeId, signal] of this.intersections.entries()) {
      signal.timeInPhase += dt;

      // 1. Measure queue lengths and detect incoming emergency vehicles
      let approachingEmergencyEdge = null;
      signal.queueLengths = {};

      for (const phase of signal.phases) {
        for (const edgeId of phase.activeEdgeIds) {
          signal.queueLengths[edgeId] = 0;
        }
      }

      for (const v of vehicles) {
        if (v.isFinished) continue;
        const edge = network.getEdge(v.currentEdgeId);
        if (!edge || edge.toNodeId !== nodeId) continue;

        if (signal.queueLengths[v.currentEdgeId] !== undefined) {
          if (v.speed < 4.0) {
            signal.queueLengths[v.currentEdgeId]++;
            this.cumulativeDelaySeconds += dt;
          }
        }

        // Emergency vehicle within 220px of intersection
        if (v.isEmergencyActive) {
          const distToStop = network.getStopLineDistance(v.currentEdgeId) - v.distanceAlongEdge;
          if (distToStop > -10 && distToStop < 220) {
            approachingEmergencyEdge = v.currentEdgeId;
          }
        }
      }

      // 2. Emergency Green-Wave Preemption
      if (approachingEmergencyEdge) {
        let matchingPhaseIndex = -1;
        for (let i = 0; i < signal.phases.length; i++) {
          if (signal.phases[i].activeEdgeIds.includes(approachingEmergencyEdge)) {
            matchingPhaseIndex = i;
            break;
          }
        }

        if (matchingPhaseIndex !== -1 && (signal.currentPhaseIndex !== matchingPhaseIndex || signal.state !== 'green')) {
          signal.currentPhaseIndex = matchingPhaseIndex;
          signal.state = 'green';
          signal.timeInPhase = 0;
          signal.isPreempted = true;
          this.emergencyPreemptionsCount++;
          this.sound.playSignalChangeChime();
          continue;
        }
      }

      // 3. Yellow Transition Countdown
      if (signal.state === 'yellow') {
        if (signal.timeInPhase >= signal.yellowTime) {
          // Switch to next phase
          signal.currentPhaseIndex = (signal.currentPhaseIndex + 1) % signal.phases.length;
          signal.state = 'green';
          signal.timeInPhase = 0;
          this.sound.playSignalChangeChime();
        }
        continue;
      }

      // 4. Normal Green Phase Decision Making
      const currentPhase = signal.phases[signal.currentPhaseIndex];
      let shouldSwitch = false;

      if (this.mode === 'fixed') {
        // Simple Fixed Clock Timers
        const targetDuration = currentPhase.duration || 18;
        if (signal.timeInPhase >= targetDuration) {
          shouldSwitch = true;
        }
      } else if (this.mode === 'actuated') {
        // Actuated Sensor Logic: switch if current green is empty and other approach has queue
        if (signal.timeInPhase >= signal.minGreen) {
          let activeQueue = 0;
          for (const edgeId of currentPhase.activeEdgeIds) {
            activeQueue += (signal.queueLengths[edgeId] || 0);
          }

          let otherQueue = 0;
          for (let pIdx = 0; pIdx < signal.phases.length; pIdx++) {
            if (pIdx === signal.currentPhaseIndex) continue;
            for (const edgeId of signal.phases[pIdx].activeEdgeIds) {
              otherQueue += (signal.queueLengths[edgeId] || 0);
            }
          }

          if ((activeQueue === 0 && otherQueue > 0) || signal.timeInPhase >= signal.maxGreen) {
            shouldSwitch = true;
          }
        }
      } else if (this.mode === 'qlearning') {
        // Reinforcement Learning Q-Decision
        if (signal.timeInPhase >= signal.minGreen) {
          let activeQueue = 0;
          for (const edgeId of currentPhase.activeEdgeIds) {
            activeQueue += (signal.queueLengths[edgeId] || 0);
          }

          let waitingQueue = 0;
          for (let pIdx = 0; pIdx < signal.phases.length; pIdx++) {
            if (pIdx === signal.currentPhaseIndex) continue;
            for (const edgeId of signal.phases[pIdx].activeEdgeIds) {
              waitingQueue += (signal.queueLengths[edgeId] || 0);
            }
          }

          const discretize = (q) => Math.min(4, Math.floor(q / 2));
          const stateKey = `${discretize(activeQueue)}_${discretize(waitingQueue)}_${signal.currentPhaseIndex % 2}`;
          const qVals = this.qTable[stateKey] || [5.0, 5.0];

          // Action 1: Switch, Action 0: Keep
          if (qVals[1] > qVals[0] || signal.timeInPhase >= signal.maxGreen) {
            shouldSwitch = true;
          }
        }
      }

      if (shouldSwitch) {
        signal.state = 'yellow';
        signal.timeInPhase = 0;
      }
    }
  }

  isEdgeRedOrAmber(edgeId, isEmergency = false) {
    if (isEmergency) return false; // Emergency vehicles run through with green preemption

    for (const signal of this.intersections.values()) {
      const activePhase = signal.phases[signal.currentPhaseIndex];
      if (activePhase.activeEdgeIds.includes(edgeId)) {
        return signal.state === 'yellow'; // Green is false (can pass), Yellow is true (stop if safe)
      }

      // Check if this edge is controlled by this intersection
      for (const phase of signal.phases) {
        if (phase.activeEdgeIds.includes(edgeId)) {
          return true; // Red
        }
      }
    }

    return false; // Not a signalized edge
  }

  getSignalStateForEdge(edgeId) {
    for (const signal of this.intersections.values()) {
      const activePhase = signal.phases[signal.currentPhaseIndex];
      if (activePhase.activeEdgeIds.includes(edgeId)) {
        return signal.state; // 'green' or 'yellow'
      }
      for (const phase of signal.phases) {
        if (phase.activeEdgeIds.includes(edgeId)) {
          return 'red';
        }
      }
    }
    return null;
  }
}
